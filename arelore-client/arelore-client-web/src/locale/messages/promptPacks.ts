const PACKS: Partial<Record<AppLocale, PromptMessages>> = {
  'zh-cn': zh,
  'en-us': en,
  'ja-jp': ja,
};

export function getPromptMessages(locale: AppLocale): PromptMessages {
  if (locale.startsWith('zh')) {
    return PACKS['zh-cn']!;
  }
  return PACKS[locale] || PACKS['en-us']!;
}
