/**
 * Generates MessageTree packs for all shell locales (except zh-cn / en-us maintained by hand).
 * Run: node scripts/gen-locale-messages.js
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '../src/locale/messages');

function varName(locale) {
  return locale.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

function toTs(locale, obj) {
  const name = varName(locale);
  const body = JSON.stringify(obj, null, 2).replace(/"([^"]+)":/g, '$1:');
  return `import { MessageTree } from './types';\n\nconst ${name}: MessageTree = ${body};\n\nexport default ${name};\n`;
}

function footer(about, privacy, terms, help) {
  return {
    createdBy: 'Arelore ©{year} Created by Arelore Team',
    about,
    privacy,
    terms,
    help,
    icp: '沪ICP备2026055763号',
  };
}

function pack({ meta, common, nav, home, products, kind, catalog, footer: ft }) {
  return { meta, common, nav, home, products, kind, catalog, footer: ft };
}

/** Catalog helper: titles stay brand-friendly; blurbs localized */
function catalogFrom(rows) {
  const out = {};
  for (const [key, title, category, blurb] of rows) {
    out[key] = { title, category, blurb };
  }
  return out;
}

